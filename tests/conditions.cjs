const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {assessWrecks}=require('../dist/hazard-model.js');
let v={wind:10,gust:15,wave:.4,current:.4,tideRate:.1,code:0};
assert.equal(assessWrecks(v).title,'No screening triggers');
assert.equal(assessWrecks({...v,current:1}).flags.includes('Regional current ≥1 kn'),true);
assert.equal(assessWrecks({...v,current:null,wind:20}).title,'Incomplete assessment');
assert.equal(assessWrecks({...v,wave:NaN}).missing.includes('wave'),true);
assert.equal(assessWrecks({...v,tideRate:-.3}).flags.includes('Tide changing ≥0.30 m/h'),true);
assert.equal(assessWrecks({...v,code:95}).flags.includes('Thunderstorm forecast'),true);
const ctx=vm.createContext({Date,console});vm.runInContext(fs.readFileSync('dist/currents.js','utf8'),ctx);
ctx.dataset=JSON.parse(fs.readFileSync('dist/data/tangalooma-tides-2026.json'));
vm.runInContext('conditionState.tides=dataset',ctx);
assert.equal(vm.runInContext("tideAt(Date.parse('2027-01-02T12:00:00+10:00'))",ctx),null);
assert.equal(vm.runInContext("tideAt(Date.parse('2025-12-31T12:00:00+10:00'))",ctx),null);
const t=vm.runInContext("tideAt(Date.parse('2026-10-24T15:00:00+10:00'))",ctx);
assert.ok(t.height>0&&Number.isFinite(t.rate));
vm.runInContext("conditionState.wind={retrievedAt:new Date(Date.now()-7*3600000).toISOString(),hourly:{time:[]}}",ctx);
assert.equal(vm.runInContext('forecastAt("wind",Date.now())',ctx),null);
vm.runInContext("conditionState.wind={retrievedAt:new Date().toISOString(),hourly:{time:['2026-10-24T15:00'],wind_speed_10m:[12]}}",ctx);
assert.equal(vm.runInContext("forecastAt('wind',Date.parse('2026-10-24T15:00:00+10:00')).wind_speed_10m",ctx),12);
assert.equal(vm.runInContext("forecastAt('wind',Date.parse('2026-10-24T16:00:00+10:00'))",ctx),null);
console.log('Passed: missing inputs, thresholds, AEST alignment, tide year bounds, stale forecasts and coverage gaps.');
